def _data_path(rel_path: str):
    """Datos administrados (galería, blog, collage, ubicación). HD_DATA_DIR permite usar una copia de los del servidor."""
    from pathlib import Path
    import os

    base = os.environ.get("HD_DATA_DIR")
    return (Path(base) if base else Path(__file__).resolve().parent) / rel_path


def _load_json_items(rel_path: str) -> list:
    import json

    path = _data_path(rel_path)
    if not path.is_file():
        return []
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return []
    items = data.get("items") if isinstance(data, dict) else None
    return items if isinstance(items, list) else []


def _load_collage(section: str) -> list:
    """Fotos del collage de una sección (se administran desde /admin/ → collage/data.json)."""
    import json

    path = _data_path("collage/data.json")
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return []
    items = data.get(section) if isinstance(data, dict) else None
    if not isinstance(items, list):
        return []
    return [i["src"] for i in items if isinstance(i, dict) and i.get("src")]


def map_query_for(data: dict) -> str:
    """Texto que se busca en Google Maps: el cargado a mano o dirección + localidad."""
    query = str(data.get("map_query") or "").strip()
    if query:
        return query
    parts = [*data.get("address_lines", []), data.get("location_label", "")]
    return ", ".join(p.strip() for p in parts if p and p.strip())


def _load_ubicacion() -> dict:
    """Dirección y mapa (se administran desde /admin/ → ubicacion/data.json)."""
    import json

    result = {
        "place_name": CONTACT["place_name"],
        "location_label": SITE["location_label"],
        "address_lines": list(CONTACT["address_lines"]),
        "map_query": CONTACT["map_query"],
    }
    path = _data_path("ubicacion/data.json")
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        data = None
    if isinstance(data, dict):
        for key in ("place_name", "location_label", "map_query"):
            if isinstance(data.get(key), str):
                result[key] = data[key].strip()
        lines = data.get("address_lines")
        if isinstance(lines, list):
            result["address_lines"] = [s.strip() for s in lines if isinstance(s, str) and s.strip()]
    result["map_q"] = map_query_for(result)
    return result


def _nav_for_page(page: str = "home") -> list:
    nav = []
    for item in NAV:
        href = item["href"]
        if page != "home":
            if href.startswith("#"):
                href = f"../{href}"
            elif href == f"{page}/":
                href = "./"
            elif not href.startswith(("http://", "https://", "../", "/")):
                href = f"../{href}"
        nav.append({**item, "href": href, "current": item["href"] == f"{page}/"})
    return nav


def _asset_version() -> str:
    from pathlib import Path
    import hashlib

    static = Path(__file__).resolve().parent / "static"
    digest = hashlib.sha1()
    for rel in ("css/styles.css", "js/main.js"):
        path = static / rel
        if path.is_file():
            digest.update(path.read_bytes())
    return digest.hexdigest()[:10]


def page_context(page: str = "home"):
    """Contexto completo para renderizar la plantilla. page: home | galeria | blog."""
    prefix = "" if page == "home" else "../"
    photos = _load_json_items("gallery/data.json")
    return {
        "site": SITE,
        "contact": CONTACT,
        "nav": _nav_for_page(page),
        "karate": {**KARATE, "collage": _load_collage("karate")},
        "historia": {**HISTORIA, "collage": _load_collage("historia")},
        "collage_data_url": f"{prefix}collage/data.json",
        "nombre": NOMBRE,
        "sensei": SENSEI,
        "valores": VALORES,
        "ubicacion": {**UBICACION, **_load_ubicacion()},
        "ubicacion_data_url": f"{prefix}ubicacion/data.json",
        "galeria": {
            **GALERIA,
            "photos": photos,
            "data_url": f"{prefix}{GALERIA['data_url']}",
            "asset_prefix": prefix,
        },
        "blog": {
            **BLOG,
            "posts": _load_json_items("blog/data.json"),
            "data_url": f"{prefix}{BLOG['data_url']}",
        },
        "page": page,
        "home_href": "#inicio" if page == "home" else "../",
        "asset_prefix": prefix,
        "asset_version": _asset_version(),
    }
